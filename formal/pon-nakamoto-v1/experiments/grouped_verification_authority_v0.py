def require(ok, code):
    if not ok:
        raise ValueError(code)


def sha(raw):
    return hashlib.sha256(raw).hexdigest()


def write_bytes(path, raw):
    with Path(path).open('xb') as handle:
        handle.write(raw)
        handle.flush()
        os.fsync(handle.fileno())
    require(Path(path).read_bytes() == raw, 'WRITE_READBACK')


def save(path, value):
    # Measurement records include finite rusage seconds. Protocol/config/plan
    # values remain integer-only and retain exactly the canonical wire bytes.
    write_bytes(path, json.dumps(value, sort_keys=True, separators=(',', ':'),
                                ensure_ascii=False, allow_nan=False).encode())


def read(path):
    return json.loads(Path(path).read_bytes(), object_pairs_hook=unique)


def operation(number):
    return sha(b'precommitted-owner-operation-v0' + number.to_bytes(8, 'big'))


def plan():
    phases = []
    def row(receiver, kind, nonce, identity, action='execute'):
        return dict(receiver=receiver, kind=kind, nonce=nonce,
                    request_id=operation(identity), action=action)
    for phase in range(1, 5):
        clients = []
        for index, receiver in enumerate((73, 74)):
            good_nonce, good_id = 2 + index, 100 + index
            if phase == 1:
                attempts = [row(receiver, 'forged_zero', 1, 10 + index * 3 + k) for k in range(3)]
                attempts += [row(receiver, 'valid', good_nonce, good_id),
                             row(receiver, 'valid', good_nonce, good_id),
                             row(receiver, 'idempotency_conflict', good_nonce, good_id)]
            elif phase == 2:
                attempts = [row(receiver, 'valid', 3 - index, 150 + index),
                            row(receiver, 'valid', good_nonce, good_id)]
                attempts += [row(receiver, 'forged_zero', 4 + index, 200 + index * 2 + k) for k in range(2)]
                attempts += [row(receiver, 'valid', 6, 300 + index, 'reserve')]
            elif phase == 3:
                attempts = [row(receiver, 'forged_zero', 7 + index, 400 + index),
                            row(receiver, 'valid', 6, 300 + index, 'reserve'),
                            row(receiver, 'valid', good_nonce, good_id)]
            else:
                attempts = [row(receiver, 'valid', 6, 300 + index)]
            clients.append(dict(receiver=receiver, attempts=attempts))
        phases.append(dict(phase=phase, clients=clients,
                           connections=sum(len(c['attempts']) for c in clients)))
    return dict(schema='pon-grouped-owner-campaign-plan-v0', aggregate_limit=12,
                per_candidate_limit=4, candidate_nonces=list(range(1, 17)),
                producer_nonces=[2, 3, 6], phases=phases,
                expected_connections=30, expected_final_reserved=12,
                expected_final_complete=11, expected_final_abandoned_reserved=1,
                expected_owner_step_queries=704, expected_producer_step_queries=192,
                no_stop_on_hit=True, thread_or_process_schedule_not_selected=True,
                simultaneous_clients_are_not_independent_operators=True,
                chainwork_awarded=0)


class Child:
    """wait4 records each child's actual full lifetime CPU independently.

    Popen.poll/wait are deliberately not used before wait4, which would discard
    the per-PID rusage. Failure and forced cancellation are recorded, not retried.
    """
    def __init__(self, argv, directory, label):
        self.directory, self.label = directory, label
        self.stdout = (directory / (label + '.stdout')).open('xb')
        self.stderr = (directory / (label + '.stderr')).open('xb')
        self.started = time.perf_counter_ns()
        self.record = dict(argv=[str(x) for x in argv], label=label, status='started')
        self.process = subprocess.Popen([str(x) for x in argv], stdin=subprocess.DEVNULL,
                                        stdout=self.stdout, stderr=self.stderr,
                                        start_new_session=True)
        self.record['pid'] = self.process.pid
        self.done = False

    def tick(self):
        if self.done:
            return True
        pid, status, usage = os.wait4(self.process.pid, os.WNOHANG)
        if not pid:
            return False
        self.done = True
        self.process.returncode = os.waitstatus_to_exitcode(status)
        for handle in (self.stdout, self.stderr):
            handle.flush()
            os.fsync(handle.fileno())
            handle.close()
        self.record.update(status='exited', exit_code=self.process.returncode,
                           lifetime_wall_ns=time.perf_counter_ns() - self.started,
                           user_seconds=usage.ru_utime, system_seconds=usage.ru_stime,
                           maxrss_kib=usage.ru_maxrss,
                           voluntary_switches=usage.ru_nvcsw, involuntary_switches=usage.ru_nivcsw)
        save(self.directory / (self.label + '.process.json'), self.record)
        return True

    def wait(self, timeout=40):
        deadline = time.monotonic() + timeout
        while not self.tick():
            if time.monotonic() >= deadline:
                self.record['cancel_reason'] = 'CONTROLLER_DEADLINE'
                os.killpg(self.process.pid, signal.SIGKILL)
                break
            time.sleep(.005)
        while not self.tick():
            time.sleep(.005)
        return self.record

    def close_if_running(self):
        if not self.tick():
            self.record['cancel_reason'] = 'CONTROLLER_FAILURE_CLEANUP'
            os.killpg(self.process.pid, signal.SIGKILL)
            self.wait(5)


def command(spec, candidates, proofs):
    candidate = candidates[spec['nonce']]
    if spec['kind'] == 'forged_zero':
        proof = (fresh.MAGIC + fresh.profile_hash() + bytes.fromhex(candidate['challenge']) +
                 bytes.fromhex(candidate['statement']) + bytes(32))
    else:
        proof = proofs[spec['nonce']]
        if spec['kind'] == 'idempotency_conflict':
            proof = proof[:-1] + bytes((proof[-1] ^ 1,))
    return dict(action=spec['action'], request_id=spec['request_id'],
                candidate=candidate['candidate'], claim=candidate['claim'], proof_hex=proof.hex())


def audit_preparation(prepared, config, init, requests):
    body_raw = bytes.fromhex(prepared['admission_pin']['body_hex'])
    body = decode_body(body_raw)
    commitments = material_commitments(init, requests, now_ns=config['freeze']['now_ns'])
    require(all(body['intent'][k] == v for k, v in commitments.items()), 'NATIVE_MATERIAL_PINS')
    require(all(r['scope']==body['intent']['authorization_scope'] for r in requests), 'AUTHORIZATION_SCOPE')
    for name, value in config['freeze'].items():
        if name != 'now_ns':
            require(body['intent'][name] == value, 'NATIVE_FREEZE_' + name)
    reference, cost = independent_reference(init, [dict(r, generation=init['model_version'],
                                                       representation=REPRESENTATION) for r in requests])
    candidates = {}
    for item in prepared['candidates']:
        nonce = item['nonce']
        candidate_bytes = CANDIDATE_MAGIC + body_raw + nonce.to_bytes(8, 'big')
        challenge = pon_hash(b'pon-grouped-fresh-challenge-v0', candidate_bytes).hex()
        work_id = pon_hash(b'pon-grouped-fresh-work-id-v0', candidate_bytes).hex()
        require(item['challenge'] == challenge and item['candidate'] == work_id, 'NATIVE_CANDIDATE_BINDING')
        context = dict(chain=body['branch']['network'], parent=body['branch']['parent'],
                       challenge=challenge, batch_id=body['intent']['batch_id'])
        binding = fresh.grouped_binding(init, requests, context, reference)
        require(item['claim']['product'] == reference and
                all(item['claim'][k] == v for k, v in binding.items()) and
                item['statement'] == binding['statement_commitment'], 'NATIVE_FULL_CELL_PREPARATION')
        require(item['target'] == body['branch']['target'], 'NATIVE_TARGET_BINDING')
        require(nonce not in candidates, 'DUPLICATE_CANDIDATE')
        candidates[nonce] = item
    require(sorted(candidates) == list(range(1, 17)), 'CANDIDATE_WINDOW')
    return candidates, dict(reference_macs=cost.reference_macs,
                            reference_additions=cost.reference_additions,
                            source_scope='one original-coefficient Python reference plus independent commitments for 16 contexts')


def audit_phase(directory, specification, reports):
    service = read(directory / 'service-report.json')
    require(service['complete'] and service['actual_connections'] == specification['connections'], 'SERVICE_DENOMINATOR')
    require(all(r['planned_attempts'] == r['actual_attempts'] and r['all_responses_authenticated_fixture'] for r in reports), 'RECEIVER_DENOMINATOR')
    require(len({r['pid'] for r in reports}) == 2, 'RECEIVERS_MUST_BE_DISTINCT_PROCESSES')
    server_pairs, client_pairs = Counter(), Counter()
    bytes_received, bytes_sent = 0, 0
    errors, new, cached, reservations = Counter(), [], [], 0
    for index, event in enumerate(service['events'], 1):
        request = (directory / f'packets/{index:04}.request.json').read_bytes()
        response = (directory / f'packets/{index:04}.response.json').read_bytes()
        require(sha(request) == event['request_sha256'] and len(request) == event['request_bytes'], 'REQUEST_READBACK')
        require(sha(response) == event['response_sha256'] and len(response) == event['response_bytes_written'], 'RESPONSE_READBACK')
        require(json.loads(response, object_pairs_hook=unique) == event['response'], 'RAW_RESPONSE_BINDING')
        server_pairs[(sha(request), sha(response))] += 1
        bytes_received += len(request)
        bytes_sent += len(response)
        body = event['response']['payload']['body']
        if not body['ok']:
            errors[body['error']] += 1
        else:
            result = body['result']
            if result['state'] == 'complete':
                (cached if result['cached'] else new).append(result['receipt'])
                if result['cached']:
                    require(result['new_step_queries'] == result['new_full_cell_calls'] == 0 and
                            result['new_candidate_completion'] is False and
                            result['cached_response_does_not_revalidate_context'] is True, 'CACHED_RESPONSE_PROMOTED')
            elif result['state'] == 'reserved':
                reservations += 1
            else:
                raise ValueError('UNEXPECTED_UNKNOWN_IN_FINITE_CAMPAIGN')
    for report in reports:
        for event in report['events']:
            request, response = bytes.fromhex(event['request_raw_hex']), bytes.fromhex(event['response_raw_hex'])
            require(event['request_bytes_written'] == len(request) and event['response_bytes'] == len(response), 'CLIENT_BYTES')
            client_pairs[(sha(request), sha(response))] += 1
    require(server_pairs == client_pairs, 'CLIENT_OWNER_RAW_BYTES_DIFFER')
    require(bytes_received == service['tcp_application_bytes_received'] and
            bytes_sent == service['tcp_application_bytes_written_known'], 'TCP_TOTALS')
    phase = specification['phase']
    expected_errors = {1: {'CandidateBudget': 2, 'IdempotencyConflict': 2},
                       2: {'CandidateClosed': 2}, 3: {'EpochBudget': 2},
                       4: {'CandidateClosed': 1}}[phase]
    require(dict(errors) == expected_errors, 'UNEXPECTED_REJECTION_SET')
    require(len(new) == {1: 6, 2: 4, 3: 0, 4: 1}[phase] and
            len(cached) == {1: 2, 2: 2, 3: 2, 4: 0}[phase] and
            reservations == {1: 0, 2: 2, 3: 2, 4: 0}[phase], 'PHASE_DISPOSITION')
    snapshot = service['snapshot']
    require(snapshot['reserved'] == {1: 6, 2: 12, 3: 12, 4: 12}[phase], 'AGGREGATE_RESERVATION_COUNT')
    require(snapshot['step_queries_known'] == {1: 384, 2: 640, 3: 640, 4: 704}[phase], 'STEP_ACCOUNTING')
    require(snapshot['step_queries_unknown_upper'] == 0 and snapshot['incomplete_cell_calls'] == 0, 'UNEXPECTED_UNKNOWN_COST')
    return dict(phase=phase, connections=specification['connections'],
                receiver_pids=[r['pid'] for r in reports], errors=dict(errors),
                new_receipts=len(new), cached_receipts=len(cached), reserve_responses=reservations,
                application_bytes_to_owner=bytes_received, application_bytes_from_owner=bytes_sent,
                cumulative_reserved=snapshot['reserved'], cumulative_owner_steps=snapshot['step_queries_known'],
                source_bytes_and_counts_verified=True)


def run(args):
    whole = time.perf_counter_ns()
    cpu = time.process_time_ns()
    child_before = resource.getrusage(resource.RUSAGE_CHILDREN)
    out = args.out.resolve()
    out.mkdir(parents=True, exist_ok=False)
    save(out / 'request.json', {k: str(v) if isinstance(v, Path) else v for k, v in vars(args).items()})
    prereg = plan()
    save(out / 'plan.json', prereg)
    plan_sha = sha((out / 'plan.json').read_bytes())
    before = source_identity(sources=SOURCES)
    binary_sha = sha(args.runner.read_bytes())
    failures = [dict(stage='source_before', **f) for f in source_gate_failures(before, args.source_sha)]
    if args.source_sha and not args.replay_source:
        failures.append(dict(stage='source_before', reason='SOURCE_REPLAY_REQUIRED'))
    children, phases, producer_trace, phases_started = [], [], [], []
    material = preparation_audit = preparation = final_snapshot = None
    try:
        require(not failures, 'SOURCE_GATE')
        start = time.perf_counter_ns()
        model, rows, provenance = load_inputs(args.model, args.tasks, args.evaluation_bundle,
            args.bundle_hash, 'consumer', 0, 16, replay_source=args.replay_source)
        init, commands = make_commands(model, rows, provenance, [16], 1, 0)
        requests = commands[0]['requests']
        commitments = material_commitments(init, requests, now_ns=1)
        material = dict(provenance=provenance, load_and_replay_wall_ns=time.perf_counter_ns()-start,
                        historical_not_new_demand=True, model_file_sha256=sha(args.model.read_bytes()),
                        tasks_file_sha256=sha(args.tasks.read_bytes()), **commitments)
        freeze = dict(**commitments, batch_id=commands[0]['context']['batch_id'],
                      authorization_scope=requests[0]['scope'],
                      demand_id=sha(b'controlled-historical-consumer-not-current-demand'),
                      source_record=sha(canonical(provenance)), withdrawal_head=sha(b'controlled-withdrawal-head'),
                      payee=sha(b'controlled-public-test-payee'), model_generation=1,
                      timestamp_ms=1_700_000_000_000, not_before_ns=1, expires_ns=3_600_000_000_000,
                      available_until_ns=3_600_000_000_000, nonce_first=1, nonce_count=16, now_ns=1)
        config = dict(schema='pon-grouped-owner-fixture-config-v0', source_commit=before['commit'],
                      clock_anchor_unix_ns=time.time_ns(), init=init, requests=requests, freeze=freeze,
                      epoch=sha(b'controlled-owner-epoch-v0' + bytes.fromhex(plan_sha)), generation=1,
                      aggregate_limit=12, per_candidate_limit=4)
        save(out / 'config.json', config)
        child = Child([args.runner.resolve(), 'prepare', out / 'owner', out / 'config.json'], out, 'prepare')
        children.append(child)
        require(child.wait(args.timeout)['exit_code'] == 0, 'OWNER_PREPARATION_EXIT')
        preparation = read(out / 'owner/preparation.json')
        require(preparation['runner_sha256'] == binary_sha and preparation['config_sha256'] == sha(canonical(config)), 'PREPARATION_IDENTITY')
        candidates, preparation_audit = audit_preparation(preparation, config, init, requests)
        proofs = {}
        for nonce in prereg['producer_nonces']:
            candidate = candidates[nonce]
            proofs[nonce] = fresh.prove(candidate['challenge'], candidate['statement'],
                on_step=lambda row, nonce=nonce: producer_trace.append(dict(nonce=nonce, **row)))
        require(len(producer_trace) == prereg['expected_producer_step_queries'], 'PRODUCER_STEPS')
        write_bytes(out / 'producer-trace.ndjson', b''.join(canonical(x)+b'\n' for x in producer_trace))
        for phase in prereg['phases']:
            number = phase['phase']
            phases_started.append(number)
            run_dir = out / f'phase-{number}'
            server = Child([args.runner.resolve(), 'serve', out / 'owner', run_dir, phase['connections']], out, f'owner-{number}')
            children.append(server)
            deadline = time.monotonic() + args.timeout
            while not (run_dir / 'endpoint.json').is_file():
                require(not server.tick(), 'OWNER_EXIT_BEFORE_ENDPOINT')
                require(time.monotonic() < deadline, 'OWNER_START_TIMEOUT')
                time.sleep(.005)
            endpoint = read(run_dir / 'endpoint.json')
            require(endpoint['policy'] == preparation['policy']['policy'] and endpoint['runner_sha256'] == binary_sha, 'OWNER_RESTART_PIN')
            clients = []
            for client in phase['clients']:
                receiver = client['receiver']
                request_path = out / f'phase-{number}-receiver-{receiver}.requests.json'
                save(request_path, [command(spec, candidates, proofs) for spec in client['attempts']])
                output = out / f'phase-{number}-receiver-{receiver}.report.json'
                process = Child([args.runner.resolve(), 'client', run_dir / 'endpoint.json', request_path, output, receiver],
                                out, f'receiver-{number}-{receiver}')
                children.append(process)
                clients.append((process, output))
            reports = []
            for process, output in clients:
                require(process.wait(args.timeout)['exit_code'] == 0, 'RECEIVER_EXIT')
                reports.append(read(output))
            require(server.wait(args.timeout)['exit_code'] == 0, 'OWNER_EXIT')
            phases.append(audit_phase(run_dir, phase, reports))
        final_snapshot = read(out / 'phase-4/service-report.json')['snapshot']
        require(final_snapshot['states'] == {'complete': 11, 'reserved': 1} and
                final_snapshot['remaining'] == 0, 'FINAL_BUDGET_DISPOSITION')
        outcomes = Counter(row['receipt']['outcome'] for row in final_snapshot['rows'] if row['receipt'])
        require(outcomes['relation_rejected'] == 8 and
                outcomes['verified_hit'] + outcomes['verified_miss'] == 3, 'FINAL_RELATIONS')
        require(sum(row['receipt']['first_record'] for row in final_snapshot['rows'] if row['receipt']) == 3,
                'CANDIDATE_DUPLICATE_COMPLETION')
    except Exception as error:
        failures.append(dict(stage='campaign', error_type=type(error).__name__, reason=str(error)))
    finally:
        for child in children:
            child.close_if_running()
    after = source_identity(sources=SOURCES)
    failures.extend(dict(stage='source_after', **f) for f in source_gate_failures(after, args.source_sha))
    if before['commit'] != after['commit'] or before['relevant_sources_sha256'] != after['relevant_sources_sha256']:
        failures.append(dict(stage='source', reason='SOURCE_CHANGED'))
    if sha(args.runner.read_bytes()) != binary_sha:
        failures.append(dict(stage='binary', reason='BINARY_CHANGED'))
    if sha((out / 'plan.json').read_bytes()) != plan_sha:
        failures.append(dict(stage='plan', reason='PLAN_CHANGED'))
    child_after = resource.getrusage(resource.RUSAGE_CHILDREN)
    record = dict(schema='pon-grouped-owner-campaign-v0', status='PASS' if not failures else 'FAIL',
        expected_source_sha=args.source_sha, exact_committed_source_verified=bool(args.source_sha and not failures),
        source_before=before, source_after=after, runner_sha256=binary_sha, plan_sha256=plan_sha,
        material=material, native_preparation=preparation, independent_preparation_audit=preparation_audit,
        phases=phases, phases_started=phases_started,
        phases_not_started=[p['phase'] for p in prereg['phases'] if p['phase'] not in phases_started],
        phases_not_completed=[p['phase'] for p in prereg['phases'] if p['phase'] not in {x['phase'] for x in phases}],
        all_processes=[c.record for c in children], final_snapshot=final_snapshot,
        producer_seed_queries=len(prereg['producer_nonces']) if len(producer_trace)==192 else None,
        producer_chain_step_queries_observed=len(producer_trace),
        forged_endpoint_producer_chain_steps=0, producer_trace_sha256=sha(b''.join(canonical(x)+b'\n' for x in producer_trace)),
        owner_preparation_processes_started=sum(c.label=='prepare' or c.label.startswith('owner-') for c in children),
        owner_preparation_reports_complete=int(preparation is not None)+sum((out/f'phase-{p["phase"]}/service-report.json').is_file() for p in prereg['phases']),
        native_source_preparation_is_assistance=True,
        expected_owner_limit=12, expected_owner_step_upper=768,
        whole_before_report_wall_ns=time.perf_counter_ns()-whole,
        parent_process_cpu_ns=time.process_time_ns()-cpu,
        all_children_user_seconds=child_after.ru_utime-child_before.ru_utime,
        all_children_system_seconds=child_after.ru_stime-child_before.ru_stime,
        cost_scope=['Per-PID wait4 includes native process loader/startup/exit; main-thread and nested phase counters must not be added again.',
            'Total child CPU additionally includes source replay and git helpers; the separately listed child rusage is a subset.',
            'Owner startup computes all 16 direct business products on each restart; this assistance is outside K and is explicitly charged.',
            'K caps expensive owner callbacks in one pinned epoch; signatures, framing, cached replies and transport remain additional costs.',
            'Step-domain queries are not all SHA256 invocations/compressions, elapsed time, energy or physical cost.',
            'Parent startup/import/exit and final report encoding are outside the reported parent interval; WAN/TLS, availability, production proofs and real authorization services are not measured.',
            'A whole-controller kill can leave process metadata/stage counts unknown; started owner rows retain conservative replay bounds.'],
        failures=failures, scope='one trusted owner across its frozen receiver registry, not public-network/Sybil/clone/rollback enforcement',
        global_public_network_cap_enforced=False, hidden_verifier_side_channels_established=False,
        independent_operators=False, external_demand_authenticated=False, physical_cost_floor_proved=False,
        neural_cost_floor_proved=False, quantum_security_proved=False, production_activation=False, chainwork_awarded=0)
    save(out / 'report.json', record)
    return record


def parser():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--out', type=Path, required=True)
    p.add_argument('--runner', type=Path, required=True)
    p.add_argument('--timeout', type=float, default=40)
    p.add_argument('--source-sha')
    p.add_argument('--replay-source', action='store_true')
    p.add_argument('--model', type=Path, default=DEFAULT_MATERIAL/'model.json')
    p.add_argument('--tasks', type=Path, default=DEFAULT_MATERIAL/'consumer.json')
    p.add_argument('--evaluation-bundle', type=Path, default=DEFAULT_MATERIAL/'evaluation-bundle.json')
    p.add_argument('--bundle-hash', default=DEFAULT_BUNDLE)
    return p


if __name__ == '__main__':
    args = parser().parse_args()
    require(1 <= args.timeout <= 60, 'CONTROLLER_TIMEOUT')
    result = run(args)
    print(json.dumps({k: result[k] for k in ('status', 'failures', 'chainwork_awarded')}, sort_keys=True))
    raise SystemExit(0 if result['status'] == 'PASS' else 2)
