use std::collections::BTreeMap;

fn calculated(arithmetic: &mut StateRootArithmetic, values: &BTreeMap<Vec<u8>, Vec<u8>>) -> Hash {
    let actual = arithmetic
        .root_from_entries(values.iter().map(|(key, value)| Ok::<_, ()>((key, value))))
        .unwrap();
    assert_eq!(actual, state_root(values).unwrap());
    assert_eq!(
        arithmetic.observation().retained_payload_bytes,
        arithmetic.retained_payload_bytes()
    );
    actual
}

fn next(seed: &mut u64) -> u64 {
    *seed ^= *seed << 13;
    *seed ^= *seed >> 7;
    *seed ^= *seed << 17;
    *seed
}

#[test]
fn complete_inputs_match_original_across_random_changes_and_reordered_rows() {
    let mut arithmetic = StateRootArithmetic::new(2 * 1024 * 1024);
    let mut values = BTreeMap::new();
    calculated(&mut arithmetic, &values);
    let mut seed = 0x2100_4080_2026_1030;
    for step in 0..96 {
        let index = next(&mut seed) % 113;
        let key = format!("namespace-{}:key-{index:03}", step % 3).into_bytes();
        if step % 7 == 0 {
            let removed = values.keys().next().cloned();
            if let Some(removed) = removed {
                values.remove(&removed);
            }
        } else {
            let length = (next(&mut seed) % 4097) as usize;
            let value = vec![(next(&mut seed) % 256) as u8; length];
            values.insert(key, value);
        }
        let root = calculated(&mut arithmetic, &values);
        if step % 11 == 0 {
            let reordered = arithmetic
                .root_from_entries(
                    values
                        .iter()
                        .rev()
                        .map(|(key, value)| Ok::<_, ()>((key, value))),
                )
                .unwrap();
            assert_eq!(reordered, root);
            assert_eq!(arithmetic.observation().computed_partitions, 0);
        }
    }
    values.clear();
    calculated(&mut arithmetic, &values);
    assert_eq!(arithmetic.retained_payload_bytes(), 0);
    assert_eq!(arithmetic.observation().input_keys, 0);
}

#[test]
fn large_values_reuse_only_identical_complete_leaf_lists() {
    let mut arithmetic = StateRootArithmetic::new(2 * 1024 * 1024);
    let mut values: BTreeMap<_, _> = (0..2100)
        .map(|index| (format!("fixture:{index:04}").into_bytes(), vec![b'x'; 4082]))
        .collect();
    let initial = calculated(&mut arithmetic, &values);
    assert_eq!(arithmetic.observation().reused_partitions, 0);
    let total = arithmetic.observation().computed_partitions;
    assert!(total > 1000 && total <= 2100);
    assert_eq!(calculated(&mut arithmetic, &values), initial);
    assert_eq!(arithmetic.observation().reused_partitions, total);
    assert_eq!(arithmetic.observation().computed_partitions, 0);
    assert!(arithmetic.retained_payload_bytes() < 300_000);

    let changed = b"fixture:1000".to_vec();
    values.get_mut(&changed).unwrap()[4070] ^= 1;
    assert_ne!(calculated(&mut arithmetic, &values), initial);
    assert_eq!(arithmetic.observation().computed_partitions, 1);
    values.remove(&changed);
    assert_ne!(calculated(&mut arithmetic, &values), initial);
    assert!(arithmetic.observation().computed_partitions <= 1);
    values.insert(changed, vec![b'x'; 4082]);
    assert_eq!(calculated(&mut arithmetic, &values), initial);
    assert_eq!(arithmetic.observation().computed_partitions, 1);
}

#[test]
fn single_partition_forks_collision_checks_and_replacement_use_original_roots() {
    let mut arithmetic = StateRootArithmetic::new(2 * 1024 * 1024);
    let mut values = BTreeMap::new();
    let mut selected = None;
    for index in 0..100_000 {
        let key = format!("collision-prefix:{index:06}").into_bytes();
        let id = prefix(&hash(b"state-key", &[&key]));
        if selected.is_none() {
            selected = Some(id);
        }
        if Some(id) == selected {
            values.insert(key, vec![(index % 256) as u8; 4096]);
            calculated(&mut arithmetic, &values);
            assert_eq!(arithmetic.observation().computed_partitions, 1);
            if values.len() == 5 {
                break;
            }
        }
    }
    assert_eq!(values.len(), 5);
    let key = values.keys().next().unwrap().clone();
    values.remove(&key);
    calculated(&mut arithmetic, &values);
    assert_eq!(arithmetic.observation().computed_partitions, 1);

    let prior = arithmetic.observation();
    // Distinct source keys with an identical hash path cannot be generated by
    // a real hash oracle. Inject the collision only through the private test
    // seam and compare the untouched original reducer's rejection.
    let colliding = vec![([7; 32], [8; 32]), ([7; 32], [9; 32])];
    assert_eq!(
        arithmetic.root_from_hashes(colliding.clone()),
        state_root_from_hashes(colliding)
    );
    assert_eq!(
        arithmetic.root_from_hashes(vec![([7; 32], [8; 32]), ([7; 32], [9; 32])]),
        Err(WireError::KeyCollision)
    );
    assert_eq!(arithmetic.observation(), prior);
    let duplicate = [(b"same".as_slice(), b"a".as_slice()), (b"same", b"b")];
    assert_eq!(
        arithmetic.root_from_entries(duplicate.into_iter().map(Ok::<_, ()>)),
        state_root_from_entries(duplicate.into_iter().map(Ok::<_, ()>))
    );
    calculated(&mut arithmetic, &values);
}

#[test]
fn incomplete_sources_and_original_wire_limits_publish_no_partial_material() {
    let mut arithmetic = StateRootArithmetic::new(2 * 1024 * 1024);
    let values: BTreeMap<_, _> = (0u64..257)
        .map(|index| (index.to_be_bytes().to_vec(), vec![b'z'; 4096]))
        .collect();
    let expected = calculated(&mut arithmetic, &values);
    let prior = arithmetic.observation();
    for cancel in [0, 1, 128, 256] {
        let entries = || {
            values.iter().enumerate().map(|(index, (key, value))| {
                assert!(index <= cancel, "source consumed after cancellation");
                if index == cancel {
                    Err("CANCELLED")
                } else {
                    Ok((key, value))
                }
            })
        };
        assert_eq!(
            arithmetic.root_from_entries(entries()),
            state_root_from_entries(entries())
        );
        assert_eq!(arithmetic.observation(), prior);
        assert_eq!(
            arithmetic.retained_payload_bytes(),
            prior.retained_payload_bytes
        );
    }
    for (key_len, value_len) in [(161, 0), (1, 4097)] {
        let entries = || [Ok::<_, ()>((vec![0; key_len], vec![0; value_len]))];
        assert_eq!(
            arithmetic.root_from_entries(entries()),
            state_root_from_entries(entries())
        );
        assert_eq!(arithmetic.observation(), prior);
    }
    let too_many = || (0u64..65_537).map(|index| Ok::<_, ()>((index.to_be_bytes(), [])));
    assert_eq!(
        arithmetic.root_from_entries(too_many()),
        state_root_from_entries(too_many())
    );
    assert_eq!(arithmetic.observation(), prior);
    assert_eq!(calculated(&mut arithmetic, &values), expected);
    assert_eq!(arithmetic.observation().computed_partitions, 0);
}

#[test]
fn retention_refusal_and_eviction_preserve_root_and_existing_budget() {
    let one_charge = std::mem::size_of::<(Hash, Hash)>() + std::mem::size_of::<Partition>();
    let mut arithmetic = StateRootArithmetic::new(one_charge);
    let mut values = BTreeMap::from([(vec![1; 160], vec![2; 4096])]);
    let initial = calculated(&mut arithmetic, &values);
    assert_eq!(arithmetic.retained_payload_bytes(), one_charge);
    values.insert(vec![3; 160], vec![4; 4096]);
    calculated(&mut arithmetic, &values);
    assert!(arithmetic.observation().retention_refused);
    assert_eq!(arithmetic.retained_payload_bytes(), 0);
    assert!(arithmetic.material.is_none());
    values.remove([3; 160].as_slice());
    assert_eq!(calculated(&mut arithmetic, &values), initial);
    assert_eq!(arithmetic.observation().reused_partitions, 0);
    assert_eq!(arithmetic.observation().computed_partitions, 1);
    let mut disabled = StateRootArithmetic::new(0);
    assert_eq!(calculated(&mut disabled, &values), initial);
    assert!(disabled.observation().retention_refused);
    assert_eq!(disabled.retained_payload_bytes(), 0);
}

#[test]
fn opaque_projection_preserves_current_inputs_empty_subsets_and_payload_edges() {
    fn reference(rows: &[(Vec<u8>, Vec<u8>)]) -> Hash {
        crate::pon_wire::state_root_from_entries(
            rows.iter()
                .map(|(k, v)| Ok::<_, &'static str>((k.as_slice(), v.as_slice()))),
        )
        .unwrap()
    }
    let rows = vec![
        (b"account:a".to_vec(), vec![1; 48]),
        (b"retained:a".to_vec(), vec![2; 4096]),
        (b"retained:z".to_vec(), vec![3; 64]),
    ];
    let selected = rows[1..].to_vec();
    for cap in [0, 63, 64, 127, 128, 2 * 1024 * 1024] {
        let mut arithmetic = StateRootArithmetic::new(cap);
        let (full, projection) = arithmetic
            .root_from_entries_with_projection(
                rows.iter()
                    .map(|(k, v)| Ok::<_, &'static str>((k.as_slice(), v.as_slice()))),
                |key| !key.starts_with(b"account:"),
            )
            .unwrap();
        assert_eq!(full, reference(&rows));
        assert_eq!(projection.is_some(), cap >= 128);
        if let Some(projection) = projection {
            assert_eq!(projection.payload_bytes(), 128);
            assert_eq!(
                arithmetic.root_from_projection(projection).unwrap(),
                reference(&selected)
            );
        }
        let (_, empty) = arithmetic
            .root_from_entries_with_projection(
                rows.iter()
                    .map(|(k, v)| Ok::<_, &'static str>((k.as_slice(), v.as_slice()))),
                |_| false,
            )
            .unwrap();
        let empty = empty.unwrap();
        assert_eq!(empty.payload_bytes(), 0);
        assert_eq!(
            arithmetic.root_from_projection(empty).unwrap(),
            reference(&[])
        );
    }
    let mut current = rows.clone();
    current[2].1[0] ^= 1;
    let mut arithmetic = StateRootArithmetic::new(2 * 1024 * 1024);
    for actual in [&rows, &current, &rows] {
        let (full, projection) = arithmetic
            .root_from_entries_with_projection(
                actual
                    .iter()
                    .map(|(k, v)| Ok::<_, &'static str>((k.as_slice(), v.as_slice()))),
                |key| !key.starts_with(b"account:"),
            )
            .unwrap();
        assert_eq!(full, reference(actual));
        assert_eq!(
            arithmetic
                .root_from_projection(projection.unwrap())
                .unwrap(),
            reference(&actual[1..])
        );
    }
}

#[test]
fn failed_complete_input_never_publishes_a_projection_or_partial_material() {
    type Row = std::result::Result<(Vec<u8>, Vec<u8>), &'static str>;
    let good: Vec<Row> = vec![Ok((b"seed".to_vec(), vec![7; 64]))];
    let mut actual = StateRootArithmetic::new(2 * 1024 * 1024);
    actual.root_from_entries(good.clone()).unwrap();
    let before = actual.observation();
    let cases: Vec<Vec<Row>> = vec![
        vec![Ok((b"a".to_vec(), vec![1])), Err("late-producer")],
        vec![Ok((vec![b'a'; 161], vec![1])), Err("late-producer")],
        vec![Err("first-producer"), Ok((vec![b'a'; 161], vec![1]))],
        vec![Ok((b"a".to_vec(), vec![0; 4097]))],
        vec![
            Ok((b"duplicate".to_vec(), vec![1])),
            Ok((b"duplicate".to_vec(), vec![2])),
        ],
    ];
    for rows in cases {
        let expected = StateRootArithmetic::new(2 * 1024 * 1024).root_from_entries(rows.clone());
        let observed = actual
            .root_from_entries_with_projection(rows, |_| true)
            .map(|value| value.0);
        assert!(observed.is_err());
        assert_eq!(
            observed.map_err(|e| format!("{e:?}")),
            expected.map_err(|e| format!("{e:?}"))
        );
        assert_eq!(actual.observation(), before);
    }
}

#[test]
fn projection_payload_limit_uses_hash_tuples_at_the_two_mib_boundary() {
    let cap = 2 * 1024 * 1024;
    let mut rows: Vec<_> = (0..cap / 64)
        .map(|index| (format!("bounded:{index:05}").into_bytes(), b"0".to_vec()))
        .collect();
    let mut arithmetic = StateRootArithmetic::new(cap);
    for expected_projection in [true, false] {
        let actual_rows = || rows.iter().map(|(key, value)| Ok::<_, ()>((key, value)));
        let expected = state_root_from_entries(actual_rows()).unwrap();
        let (full, projection) = arithmetic
            .root_from_entries_with_projection(actual_rows(), |_| true)
            .unwrap();
        assert_eq!(full, expected);
        assert_eq!(projection.is_some(), expected_projection);
        if let Some(projection) = projection {
            assert_eq!(projection.payload_bytes(), cap);
            assert_eq!(
                arithmetic.root_from_projection(projection).unwrap(),
                expected
            );
        }
        rows.push((b"bounded:extra".to_vec(), b"0".to_vec()));
    }
}
